type Key = keyof typeof strings;
/** Keys that have _one / _other variants, addressed without the suffix. */
export type PluralKey = { [K in Key]: K extends `${infer Base}_one` ? Base : never }[Key];

const plural = new Intl.PluralRules('en');
const fill = (s: string, vars: Record<string, string | number>) =>
  s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return fill(strings[key], vars);
}

/** Plural lookup: picks `${key}_one` or `${key}_other` from `count` and exposes {count}. */
export function tp(key: PluralKey, count: number, vars: Record<string, string | number> = {}): string {
  const form = plural.select(count) === 'one' ? 'one' : 'other';
  return fill(strings[`${key}_${form}` as Key], { count, ...vars });
}
